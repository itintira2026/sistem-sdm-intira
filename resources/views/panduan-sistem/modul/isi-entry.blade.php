<h4>Kolom Perlu Dikerjakan Hari Ini</h4>
<p>Bagian <strong>Perlu Dikerjakan Hari Ini</strong> menampilkan Tugas KPI yang masih aktif. Persentase di samping judul
    menunjukkan progres tugas; entry yang perlu diisi atau diperbaiki ditampilkan lebih dahulu. Klik judul untuk membuka
    detail tugas. Tugas yang dibekukan atau dinonaktifkan ditandai dan tidak memiliki aksi isi.</p>
<h4>Cara mengisi</h4>
<p>Klik <strong>Isi Sekarang</strong> untuk entry baru, <strong>Ubah</strong> untuk memperbarui entry yang masih
    menunggu validasi, atau <strong>Perbaiki</strong> jika entry ditolak. Form terbuka dalam modal. Untuk input angka,
    preview di bawah kolom nilai menunjukkan format satuan dan perbandingan dengan target; nilai 150% atau lebih dari
    target diberi peringatan untuk diperiksa kembali. Klik <strong>Simpan</strong> untuk mengirim entry.</p>
<h4>Lampiran</h4>
<p>Lampiran bersifat opsional. Tipe yang didukung: JPG, JPEG, PNG, PDF, XLSX, XLS, CSV, MP4, MOV, dan AVI. Ikuti batas
    pada form: gambar/dokumen maksimal 3 MB dan video maksimal 20 MB. Lampiran yang sudah diunggah dapat dibuka dari
    tautan nama file.</p>
<h4>Kalau entry ditolak</h4>
<p>Alasan penolakan terlihat di form. Perbaiki nilai atau lampiran, lalu simpan kembali. Entry dikirim ulang ke status
    menunggu validasi dan diproses kembali oleh pemeriksa/approver yang berwenang. Entry ditolak dapat diperbaiki kapan
    saja selama tugas belum dinonaktifkan atau dibekukan.</p>
<h4 class="font-semibold">Kenapa entry kemarin tidak bisa diisi</h4>
<p class="text-rose-500">Entry Harian berstatus pending hanya bisa diisi tepat pada tanggal yang tercantum. Jika tanggal
    lewat tanpa entry yang disetujui, hari tersebut dihitung belum tercapai dalam progres. Entry yang ditolak tetap bisa
    diperbaiki meski tanggalnya sudah lewat.</p>
