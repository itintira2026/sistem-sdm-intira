<h4>Membuka antrian Perlu Saya Cek</h4>
<p>Buka menu <strong>Perlu Saya Cek</strong> di sidebar untuk melihat entry tugas yang menunggu tindakan dan berada
    dalam kewenangan Anda. Entry tanpa bobot tidak memerlukan validasi. Dalam alur normal, entry yang belum diisi atau
    tanggal entry-nya belum tiba belum dapat dicek.</p>
<h4>Membaca highlight target</h4>
<p>Untuk entry numerik yang memiliki target individu, highlight menunjukkan perbandingan nilai dengan target: kuning
    berarti masih di bawah target, hijau berarti sesuai atau melampaui target, dan merah berarti nilainya jauh di atas
    target (150% atau lebih) sehingga perlu dicek ulang karena mungkin salah input. Entry checklist atau yang tidak
    memiliki target numerik tidak menampilkan perbandingan ini.</p>
<h4>Melihat lampiran</h4>
<p>Klik nama file pada bagian lampiran untuk membuka bukti di tab baru. Jika tertulis <em>Tanpa lampiran</em>, tidak ada
    bukti yang dilampirkan pada entry tersebut. Tombol <strong>Detail</strong> membuka halaman tugas di tab baru.</p>
<h4>Lolos cek atau tolak</h4>
<p>Pilih satu atau beberapa entry, tentukan hasil <strong>Lolos Cek</strong> atau <strong>Tolak</strong>, lalu klik
    <strong>Proses</strong>. Gunakan <strong>Pilih Semua</strong> bila ingin memilih seluruh entry yang tampil. Jika
    menolak, isi <strong>Alasan</strong> karena wajib; saat memproses beberapa entry sekaligus, hasil dan alasan yang
    sama diterapkan pada semua pilihan.
</p>
<h4>Apa yang terjadi setelahnya</h4>
<p>Untuk entry FO, <strong>Lolos Cek</strong> oleh AM meneruskan entry ke tahap approve Korwil; jika ditolak, entry
    kembali ke pengisi untuk diperbaiki dan dikirim ulang. Korwil juga dapat memberi keputusan approve atau menolak
    langsung. Untuk entry selain FO, tidak ada tahap cek terpisah: <strong>Lolos Cek</strong> langsung menyetujui entry,
    sedangkan <strong>Tolak</strong> mengembalikannya kepada pengisi.</p>
