<h4>Mengatur role KPI dan divisi</h4>
<p>Cari user berdasarkan nama atau username, lalu klik <strong>Atur Role KPI</strong>. Pilih satu role struktural atau
    <strong>Tidak ada</strong>. Divisi wajib dipilih jika role-nya Kadiv atau Staff. Centang <strong>Korwil</strong>
    bila diperlukan; Korwil adalah role tambahan untuk user Manager, bukan pengganti role dasar. Halaman ini tidak
    mengubah role dasar seperti AM atau FO.</p>
<h4>Efek pembekuan otomatis</h4>
<p>Jika role struktural, divisi, atau status Korwil berubah, semua penugasan Tugas KPI aktif user yang belum dikunci
    otomatis dibekukan. Persentase progres saat perubahan menjadi nilai final, user tidak dapat mengirim entry baru
    untuk penugasan tersebut, dan penugasan yang dibekukan tidak lagi masuk hitungan KPI bulanan. Pembekuan mengikuti
    semua tugas berstatus aktif, tanpa membatasi berdasarkan tanggal akhir periode.</p>
<h4>Alur memindahkan jabatan</h4>
<p>Sebelum mengubah cabang atau role dasar AM/FO melalui Manajemen User, nonaktifkan lebih dahulu tugas yang tidak lagi
    perlu dikerjakan dari halaman Atur Bobot. Perubahan role dasar atau cabang di Manajemen User tidak menjalankan
    pembekuan otomatis. Setelah itu, atur role KPI/divisi melalui halaman ini; perubahan role struktural, divisi, atau
    Korwil akan membekukan penugasan KPI aktif secara otomatis.</p>
