<h4>Apa itu Tugas KPI dan Tugas Tambahan</h4>
<p><strong>Tugas KPI</strong> diberikan oleh atasan, memiliki bobot, dan entry-nya melalui validasi. <strong>Tugas
        Tambahan</strong> adalah catatan aktivitas pribadi di luar penugasan atasan; tidak berbobot, tidak divalidasi,
    dan tidak masuk perhitungan KPI, tetapi tetap dapat dilihat atasan.</p>
<h4>Istilah penting</h4>
<p><strong>Bobot</strong> menentukan kontribusi tugas pada KPI; total bobot tugas aktif seseorang harus 100% untuk paket
    bulan terkait. <strong>Target</strong> adalah nilai yang ditetapkan per orang dan dapat berbeda antar penerima. Mode
    tugas: <strong>Sekali</strong> untuk satu entry, <strong>Harian</strong> untuk entry pada hari kerja yang ditandai,
    dan <strong>Kumulatif</strong> untuk satu nilai total terhadap target.</p>
<h4>Status entry</h4>
<p><strong>Pending</strong> berarti menunggu validasi. Pada entry FO, <strong>Dicek</strong> berarti lolos pemeriksaan
    AM dan menunggu approve final Korwil. <strong>Disetujui</strong> berarti validasi selesai; entry baru berkontribusi
    pada KPI jika progresnya memenuhi aturan target. <strong>Ditolak</strong> berarti pengisi perlu memperbaiki dan
    mengirim ulang. Tugas Tambahan tidak memiliki status validasi.</p>
<h4>Alur besar</h4>
<p>Atasan membuat Tugas KPI dan menetapkan target per orang, lalu mengatur bobot agar totalnya 100%. Pengisi mengirim
    entry sesuai mode tugas. Entry FO dicek AM dan di-approve Korwil; Korwil dapat mengambil keputusan langsung. Entry
    role lain diproses oleh approver yang berwenang tanpa tahap cek terpisah. Progres yang memenuhi aturan validasi dan
    target dihitung ke KPI berdasarkan bulan tanggal selesai tugas.</p>
