<h4>Mengoreksi entry</h4>
<p>Di bagian <strong>Cari Entry untuk Dikoreksi</strong>, cari berdasarkan nama orang atau judul tugas, lalu saring
    dengan status dan rentang tanggal bila perlu. Klik <strong>Koreksi</strong> pada entry yang tepat. Superadmin dapat
    memperbarui nilai angka atau checklist, dan status validasi untuk entry KPI. Tugas Tambahan (self-record) hanya
    dapat dikoreksi nilainya. Isi <strong>Alasan Koreksi</strong> yang wajib; perubahan dicatat sebagai <em>Dikoreksi
        oleh Superadmin</em> di audit trail. Jika progres sudah difinalisasi, sistem menghitung ulang KPI terkait
    setelah koreksi disimpan.</p>
<h4>Panel Koreksi Data</h4>
<p>Panel juga memiliki bagian <strong>Tugas Terhapus</strong>. Cari judul tugas, periksa pembuat, jumlah assignee, dan
    waktu penghapusan, lalu klik <strong>Pulihkan</strong> untuk mengembalikannya. Entry terbaru ditampilkan bila filter
    tidak dipakai; hasil dapat difilter berdasarkan nama/judul, status termasuk Self-record, serta tanggal entry. Tugas
    yang dipulihkan dan entry yang dikoreksi tetap mengikuti catatan sistem masing-masing.</p>
