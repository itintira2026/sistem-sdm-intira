<h4>Membaca halaman KPI Tim</h4>
<p>Gunakan navigasi bulan untuk melihat KPI pada bulan yang dipilih dan kotak pencarian untuk mencari nama. Anggota
    ditampilkan dalam grup <strong>Head Office</strong> dan <strong>Lapangan</strong>, masing-masing dengan ringkasan
    rata-rata, jumlah orang, jumlah KPI minimal 80%, dan jumlah KPI di bawah 40%. Ringkasan kedua grup dihitung
    terpisah, bukan digabung.</p>
<h4>Arti warna dan badge bobot</h4>
<p>Warna persentase KPI per orang: hijau untuk 80% atau lebih, kuning untuk 50% sampai kurang dari 80%, dan merah untuk
    kurang dari 50%. Ambang ini berbeda dari angka pada ringkasan, yang menghitung minimal 80% dan di bawah 40%. Badge
    <strong>Bobot</strong> hijau berarti total bobot Tugas KPI aktif orang tersebut sudah 100%; badge peringatan berarti
    belum. Badge bobot menunjukkan kondisi tugas aktif saat ini, bukan kondisi historis dari bulan yang sedang dipilih.
</p>
<h4>Mode preview</h4>
<p>Label <em>(preview)</em> berarti Anda dapat melihat KPI orang tersebut, tetapi tidak mengelola tugasnya dari halaman
    ini. Kadiv dan Staff dapat melihat grup Lapangan sebagai preview; untuk Kadiv, anggota Staff di divisinya sendiri
    tetap berada dalam lingkup kelola. Korwil melihat AM dan FO di cabang yang dikelolanya, sedangkan Owner, Ketua, dan
    Direktur dapat melihat kedua grup.</p>
<h4>Halaman detail per orang</h4>
<p>Klik nama untuk membuka detail yang hanya bisa dilihat. Halaman ini menampilkan total KPI bulan terpilih, rincian
    tiap tugas beserta bobot, target, progres, kontribusi, dan detail entry. Bagian <strong>Tugas Tambahan</strong>
    ditampilkan terpisah karena tidak masuk KPI. Nilai input tugas mode Sekali dan Kumulatif ditampilkan bersama status
    validasi; pada detail harian, latar merah berarti target hari itu belum tercapai atau entry belum disetujui. Gunakan
    navigasi bulan untuk berpindah periode.</p>
