<h4>Siapa meng-approve siapa</h4>
<ul>
    <li>Korwil meng-approve entry FO dan AM di cabang yang sama.</li>
    <li>Kadiv meng-approve entry Staff di divisi yang sama.</li>
    <li>Ketua atau Direktur meng-approve entry Kadiv dan Korwil.</li>
</ul>
<h4>Membuka antrian Perlu Saya Approve</h4>
<p>Buka menu <strong>Perlu Saya Approve</strong> di sidebar. Antrian menampilkan entry Tugas KPI yang sudah diisi, belum
    disetujui atau ditolak, dan berada dalam kewenangan Anda. Badge <em>sudah dicek AM</em> dan <em>belum dicek</em>
    menunjukkan status cek. Korwil dapat meng-approve entry FO yang belum dicek AM tanpa menunggu tahap cek. Tugas tanpa
    bobot tidak masuk antrian ini.</p>
<h4>Approve atau tolak</h4>
<p>Pilih satu atau beberapa entry, tentukan <strong>Setujui</strong> atau <strong>Tolak</strong>, lalu klik
    <strong>Proses</strong>. Gunakan <strong>Pilih Semua</strong> untuk memilih seluruh entry yang tampil. Jika menolak,
    isi <strong>Alasan</strong> karena wajib; bila memproses beberapa entry sekaligus, keputusan dan alasan yang sama
    diterapkan ke semua pilihan.</p>
<h4>Approve bukan berarti target tercapai</h4>
<p>Approve berarti entry lolos validasi, bukan otomatis targetnya tercapai. Capaian tetap dihitung dengan membandingkan
    nilai terhadap target. Contoh: nilai Rp500.000 dengan target Rp1.000.000 tetap baru mencapai 50%, meskipun entry
    sudah di-approve.</p>
<h4>Entry yang sudah disetujui</h4>
<p>Setelah disetujui, entry terkunci dan pengisi tidak dapat mengubahnya lagi. Jika entry ditolak, pengisi dapat
    memperbaiki dan mengirim ulang untuk diproses kembali.</p>
