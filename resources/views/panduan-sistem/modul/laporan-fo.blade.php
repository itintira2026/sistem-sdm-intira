<h4>Mengisi laporan</h4>
<p>FO mengisi laporan untuk setiap slot 4 jam. Laporan hanya dapat diisi atau diedit selama batas waktu pengisian slot
    masih terbuka.</p>
<h4>Edit dan validasi</h4>
<p>Validasi melibatkan dua tahap: check oleh AM dan approve final oleh Korwil. Setelah dicek oleh AM, laporan menunggu
    keputusan Korwil; Korwil juga dapat memberi keputusan secara langsung. Jika laporan ditolak oleh AM atau Korwil,
    form edit dibuka kembali meskipun batas waktu slot telah habis. FO dapat memperbaiki dan mengirim ulang laporan
    dalam 3×24 jam sejak penolakan, lalu laporan diproses kembali. Tombol Edit tersedia di halaman history selama
    periode tersebut dan menjadi nonaktif setelah batas waktu berakhir.</p>
