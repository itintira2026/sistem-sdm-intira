<h4>Melihat ukuran lampiran</h4>
<p>Atur rentang tanggal pada kolom <strong>Diupload dari</strong> dan <strong>Sampai</strong>, lalu klik
    <strong>Terapkan</strong>. Pintasan menampilkan lampiran yang lebih lama dari 3 bulan, 6 bulan, atau 1 tahun. Tanpa
    filter, daftar awalnya menampilkan lampiran yang diunggah lebih dari 6 bulan lalu. Ringkasan memperlihatkan jumlah
    file, total ukuran, dan rentang; daftar menampilkan nama file, tugas, pengunggah, tanggal, dan ukuran.</p>
<h4>Menghapus lampiran</h4>
<p>Pastikan rentang tanggal benar dan kolom <strong>Sampai</strong> terisi, lalu klik <strong>Hapus lampiran</strong>.
    Penghapusan berlaku untuk semua lampiran dalam rentang tersebut, bukan hanya file yang sedang terlihat di halaman.
    Isi alasan wajib. Jika rentang menyentuh lampiran dari 6 bulan terakhir, centang konfirmasi tambahan. Tindakan ini
    menghapus permanen data dan file fisiknya, tidak dapat dibatalkan, dan dicatat di log.</p>
