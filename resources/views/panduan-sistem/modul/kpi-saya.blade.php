<h4>Membaca total KPI bulan ini</h4>
<p><strong>Total KPI Bulan Ini</strong> adalah jumlah kontribusi tugas berbobot pada bulan yang dipilih, dihitung live
    dari data terbaru. Tugas masuk ke bulan berdasarkan tanggal selesai; misalnya tugas 30 September–1 Oktober dihitung
    pada Oktober. Progres tugas yang dibekukan atau dinonaktifkan tidak masuk total KPI.</p>
<h4>Breakdown per tugas</h4>
<p>Setiap tugas menampilkan rentang periode, bobot, target, persentase progres, dan kontribusi ke total. Kontribusi
    dihitung dari persentase progres dikalikan bobot; contohnya progres 50% dengan bobot 20% menyumbang 10 poin
    persentase. Tugas beku ditandai ikon kunci; progres finalnya dapat tetap terlihat di rincian meski tidak dihitung ke
    total. Pada tugas mode Sekali dan Kumulatif, nilai input, status validasi, dan lampiran ditampilkan di bawah rincian
    tugas.</p>
<h4>Detail Harian</h4>
<p>Pada tugas mode Harian, klik <strong>Detail Harian</strong> untuk membuka daftar tanggal, nilai, lampiran, dan badge
    status. Badge menunjukkan apakah entry masih pending, sudah dicek, disetujui, atau ditolak. Latar hijau berarti
    target hari itu tercapai dan entry disetujui. Latar merah berarti target belum tercapai atau entry belum disetujui.</p>
<h4>Berpindah bulan</h4>
<p>Gunakan tombol <strong>Sebelumnya</strong> dan <strong>Berikutnya</strong> untuk berpindah bulan dan melihat total
    serta breakdown KPI pada periode tersebut.</p>
