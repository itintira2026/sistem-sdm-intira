<h4>Mengatur bobot</h4>
<p>Dari halaman <strong>Tim &amp; Tugas yang Saya Berikan</strong>, pilih <strong>Atur Bobot</strong> pada anggota tim.
    Isi bobot untuk semua Tugas KPI aktif yang berakhir pada bulan berjalan. Indikator <strong>Total Bobot</strong> di
    bagian atas berubah langsung saat angka diubah; total harus tepat 100% agar dapat disimpan.</p>
<h4>Mengoreksi target</h4>
<p>Target tiap tugas dapat dikoreksi pada form yang sama dan disimpan bersama bobot. Target hanya tersedia untuk tugas
    numerik; tugas checklist tidak memiliki target numerik. Walaupun hanya mengoreksi target, pastikan semua bobot yang
    tampil tetap terisi dan totalnya 100% sebelum menyimpan.</p>
<h4>Menonaktifkan tugas seseorang</h4>
<p>Gunakan <strong>Nonaktifkan</strong> pada tugas milik orang tersebut jika ia tidak lagi perlu mengerjakannya. Isi
    alasan yang diminta. Progres dikunci pada angka saat ini, orang tersebut tidak dapat mengirim entry baru untuk tugas
    itu, dan tugas dikeluarkan dari hitungan bobot serta antrian validasi. Riwayat entry dan validasi yang sudah ada
    tetap tersimpan. Setelah menonaktifkan, sesuaikan bobot tugas aktif lainnya agar totalnya kembali 100%.</p>
<h4>Sebelum memindahkan jabatan seseorang</h4>
<p>Nonaktifkan terlebih dahulu tugas yang tidak lagi perlu dikerjakan orang tersebut, lalu ubah jabatannya. Setelah role
    berubah, atasan lama mungkin tidak lagi memiliki akses untuk mengelola tugas itu; penonaktifan lebih dulu memastikan
    progres dan alasannya tercatat. Jika role berubah sebelum tugas dinonaktifkan, sistem membekukan tugas dan
    progresnya secara otomatis.</p>
<h4>Halaman Tugas yang Diberikan</h4>
<p>Di bagian <strong>Bobot KPI Tim</strong>, setiap anggota menampilkan jumlah tugas aktif dan status total bobot: badge
    hijau menandakan 100%, sedangkan badge peringatan menunjukkan total belum pas atau ada tugas yang belum diberi
    bobot. Klik <strong>Atur Bobot</strong> untuk mengubahnya. Bagian <strong>Tugas yang Saya Buat</strong> menampilkan
    tugas dan assignee yang belum mendapat bobot; jika tugas diberikan kepada beberapa orang, tersedia tautan
    <strong>Status bobot</strong>.</p>
