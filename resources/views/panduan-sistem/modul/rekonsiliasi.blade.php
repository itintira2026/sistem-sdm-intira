<h4>Membuka dan memfilter</h4>
<p>Buka halaman <strong>Rekonsiliasi FO vs Data Resmi</strong>. Pilih cabang atau <strong>Semua Cabang</strong>, lalu
    tentukan tanggal dari dan sampai. Filter diterapkan otomatis. Jika rentang mencakup lebih dari satu hari, nilai yang
    ditampilkan adalah total selama rentang tersebut. Perbandingan laporan FO hanya mengambil laporan yang sudah
    disetujui.</p>
<h4>Membaca hasilnya</h4>
<p>Setiap FO memiliki perbandingan <strong>Omset</strong> dan <strong>Revenue</strong> masing-masing: <em>Sesuai</em>
    berarti nilainya sama dengan data resmi, <em>Lebih</em> berarti nilai laporan FO lebih besar, dan <em>Kurang</em>
    berarti lebih kecil. Jika belum ada data resmi untuk FO tersebut, nilainya ditampilkan sebagai tanda — dan status
    metrik belum tersedia. Ringkasan <strong>Sesuai</strong> berarti kedua metrik cocok; <strong>Ada Selisih</strong>
    berarti setidaknya satu berbeda; <strong>Belum Ada Data</strong> berarti data resmi belum tersedia. Halaman ini
    hanya untuk pemantauan dan tidak mengubah data secara otomatis.</p>
