<h4>Menandai hari kerja</h4>
<p>Gunakan tombol <strong>Bulan Sebelumnya</strong> dan <strong>Bulan Berikutnya</strong> untuk membuka kalender. Klik
    tanggal untuk menandainya sebagai hari kerja; klik lagi untuk membatalkan tanda. Jumlah hari yang ditandai terlihat
    pada <strong>Total Hari Kerja Bulan Ini</strong>. Sabtu dan Minggu tetap bisa ditandai bila diperlukan.</p>
<h4>Tandai SEBELUM tugas harian dibuat</h4>
<p>Untuk tugas KPI bermode <strong>Harian</strong>, entry dibuat otomatis dari tanggal yang sudah ditandai sebagai hari
    kerja dalam periode tugas saat tugas dibuat. Karena itu, tandai kalender lebih dahulu. Menandai tanggal setelah
    tugas dibuat tidak membuat entry baru untuk tugas tersebut.</p>
<h4>Libur mendadak</h4>
<p>Jika hari kerja berubah menjadi libur, klik tanggal itu untuk menghapus tandanya. Tanggal tersebut tidak lagi masuk
    perhitungan progres harian, sehingga tidak menurunkan persentase karena entry yang tidak dikerjakan. Baris entry
    yang telanjur dibuat tetap tersimpan, tetapi tanggal yang tidak lagi ditandai diabaikan dalam perhitungan.</p>
