<h4>Siapa boleh memberi tugas ke siapa</h4>
<p>Hak memberi Tugas KPI mengikuti role dan lingkup kerja: Ketua/Direktur dapat memberi tugas kepada Kadiv atau Korwil;
    Kadiv kepada Staff di divisi yang sama; Korwil kepada AM atau FO di cabang yang dikelolanya. Daftar penerima di form
    otomatis mengikuti kewenangan Anda.</p>
<h4>Mengisi form</h4>
<p>Isi <strong>Judul Tugas</strong>, lalu pilih cara tracking: <strong>Numeric</strong> untuk nilai angka atau
    <strong>Checklist</strong> untuk status ya/tidak. Untuk numeric, pilih satuan angka biasa, Rupiah, atau persen;
    label satuan bebas tersedia untuk angka biasa. Pilih mode <strong>Sekali</strong> untuk satu entry,
    <strong>Harian</strong> untuk entry pada setiap tanggal yang ditandai sebagai hari kerja, atau
    <strong>Kumulatif</strong> untuk satu nilai total. Tentukan periode mulai dan selesai. Ruang lingkup divisi dan
    tugas referensi bersifat opsional.</p>
<h4>Target per orang</h4>
<p>Pilih penerima tugas, lalu isi target masing-masing bila diperlukan. Target boleh berbeda untuk tiap orang; preview
    di bawah input mengikuti format satuan, seperti Rp atau persen. Target persen maksimal 100%. Untuk tugas numeric
    tanpa target, nilai di atas 0 dianggap tercapai pada mode Sekali dan Harian; mode Kumulatif memerlukan target untuk
    menghitung progres. Entry baru dihitung dalam KPI setelah disetujui.</p>
<h4>Salin dari tugas sebelumnya</h4>
<p>Ketik minimal dua huruf awal judul untuk mencari tugas sebelumnya yang pernah Anda buat, lalu pilih hasilnya untuk
    menyalin judul, deskripsi, cara tracking, satuan, mode, dan ruang lingkup divisi. Hasil pencarian menampilkan
    maksimal 20 tugas yang cocok. Periode, penerima, target per orang, bobot, serta tugas referensi tidak ikut tersalin;
    isi atau pilih kembali bagian tersebut sesuai kebutuhan.</p>
<h4>Setelah disimpan</h4>
<p>Tugas KPI yang baru dibuat belum memiliki bobot. Jika hanya satu orang yang dipilih, Anda langsung diarahkan ke
    halaman <strong>Atur Bobot</strong> orang tersebut. Jika beberapa orang dipilih, halaman status bobot menampilkan
    tautan pengaturan untuk masing-masing orang. Atur bobot semua Tugas KPI aktif tiap orang hingga totalnya tepat 100%.
</p>
